from typing import List, Dict, Any, Tuple
from app.schemas.chat import Citation

class CitationValidator:
    """
    Independently verifies that all citations generated by the tutor or assessment
    engine originate from verified, existing chunks in the retrieved context,
    preventing hallucinated references.
    """

    @staticmethod
    def validate_citations(
        raw_citations: List[Dict[str, Any]],
        retrieved_chunks: List[Dict[str, Any]]
    ) -> Tuple[List[Citation], float]:
        """
        Returns validated Citation objects and a citation validity rate in [0.0, 1.0].
        """
        valid_chunk_map = {c["chunk_id"]: c for c in retrieved_chunks}
        validated_list: List[Citation] = []
        valid_count = 0

        for idx, cit in enumerate(raw_citations):
            chunk_id = cit.get("chunk_id", "")
            chunk = valid_chunk_map.get(chunk_id)

            if chunk:
                # Verified against indexed chunk
                valid_count += 1
                page_no = chunk.get("page_number")
                slide_no = chunk.get("slide_number")
                t_start = chunk.get("timestamp_start")
                t_end = chunk.get("timestamp_end")
                source_name = chunk.get("source_name", "Unknown Source")
                source_id = chunk.get("source_id", "")
                source_type = chunk.get("source_type", "pdf")

                # Excerpt check: pick first 180 characters or matching sentence
                excerpt = cit.get("excerpt") or chunk.get("content", "")[:180] + "..."

                validated_list.append(Citation(
                    citation_id=f"cit_{idx+1}",
                    source_id=source_id,
                    source_name=source_name,
                    source_type=source_type,
                    chunk_id=chunk_id,
                    page_number=page_no,
                    slide_number=slide_no,
                    timestamp_start=t_start,
                    timestamp_end=t_end,
                    excerpt=excerpt,
                    relevance_score=float(cit.get("relevance_score", 1.0)),
                    verification_status="verified"
                ))
            else:
                # Flagged hallucination/unverified chunk reference
                validated_list.append(Citation(
                    citation_id=f"cit_{idx+1}",
                    source_id=cit.get("source_id", "unverified"),
                    source_name=cit.get("source_name", "Unverified Source"),
                    source_type=cit.get("source_type", "unknown"),
                    chunk_id=chunk_id,
                    excerpt=cit.get("excerpt", "Citation could not be resolved in active course chunks."),
                    relevance_score=0.0,
                    verification_status="unverified"
                ))

        total = len(raw_citations)
        validity_rate = (valid_count / total) if total > 0 else 1.0
        return validated_list, validity_rate
